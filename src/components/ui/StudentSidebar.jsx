export default function StudentSidebar({
  activeTab,
  onSelectTab,
  currentUser,
  currentTheme,
  onThemeChange,
  onNavigateHome,
  onLogout
}) {
  const userName = currentUser?.fullName || 'Student';
  const userRole = 'Student Persona';
  const userInitials = userName
    .split(' ')
    .filter(Boolean)
    .map((n) => n[0])
    .join('')
    .substring(0, 2)
    .toUpperCase() || 'ST';

  const toggleTheme = () => {
    if (onThemeChange) {
      onThemeChange(currentTheme === 'dark' ? 'light' : 'dark');
    }
  };

  return (
    <aside className="student-sidebar" aria-label="Student Navigation">
      {/* 1. Header with Logo & Brand */}
      <div className="student-sidebar-header">
        <button
          type="button"
          className="student-sidebar-brand"
          onClick={onNavigateHome}
          title="TalentOrbit Homepage"
        >
          <div className="student-sidebar-logo">
            <svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
              <circle cx="12" cy="12" r="10" />
              <path d="M12 2a14.5 14.5 0 0 0 0 20 14.5 14.5 0 0 0 0-20" />
              <path d="M2 12h20" />
            </svg>
          </div>
          <div className="student-sidebar-brand-meta">
            <span className="student-sidebar-title">TalentOrbit</span>
            <span className="student-sidebar-persona-badge">Student Portal</span>
          </div>
        </button>
      </div>

      {/* 2. Scrollable Navigation Menu */}
      <nav className="student-sidebar-content">
        {STUDENT_NAV_ITEMS.map((section) => (
          <div key={section.group} className="student-sidebar-group">
            <div className="student-sidebar-group-label">{section.group}</div>
            {section.items.map((item) => {
              const isActive = activeTab === item.id;
              return (
                <button
                  key={item.id}
                  type="button"
                  onClick={() => onSelectTab(item.id)}
                  className={`student-sidebar-item ${isActive ? 'active' : ''}`}
                  aria-current={isActive ? 'page' : undefined}
                >
                  <div className="student-sidebar-item-left">
                    <span className="student-sidebar-item-icon">{item.icon}</span>
                    <span>{item.label}</span>
                  </div>
                </button>
              );
            })}
          </div>
        ))}
      </nav>

      {/* 3. Footer with Profile, Theme & Actions */}
      <div className="student-sidebar-footer">
        <div className="student-sidebar-user-card">
          <div className="student-sidebar-avatar">{userInitials}</div>
          <div className="student-sidebar-user-info">
            <span className="student-sidebar-user-name">{userName}</span>
            <span className="student-sidebar-user-role">{userRole}</span>
          </div>
        </div>

        <div className="student-sidebar-footer-actions">
          <button
            type="button"
            className="student-sidebar-footer-btn"
            onClick={toggleTheme}
            title={currentTheme === 'dark' ? 'Switch to Light Mode' : 'Switch to Dark Mode'}
          >
            {currentTheme === 'dark' ? (
              <>
                <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
                  <circle cx="12" cy="12" r="5" />
                  <line x1="12" y1="1" x2="12" y2="3" />
                  <line x1="12" y1="21" x2="12" y2="23" />
                  <line x1="4.22" y1="4.22" x2="5.64" y2="5.64" />
                  <line x1="18.36" y1="18.36" x2="19.78" y2="19.78" />
                  <line x1="1" y1="12" x2="3" y2="12" />
                  <line x1="21" y1="12" x2="23" y2="12" />
                  <line x1="4.22" y1="19.78" x2="5.64" y2="18.36" />
                  <line x1="18.36" y1="5.64" x2="19.78" y2="4.22" />
                </svg>
                <span>Light</span>
              </>
            ) : (
              <>
                <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
                  <path d="M21 12.79A9 9 0 1 1 11.21 3 7 7 0 0 0 21 12.79z" />
                </svg>
                <span>Dark</span>
              </>
            )}
          </button>

          <button
            type="button"
            className="student-sidebar-footer-btn"
            onClick={onNavigateHome}
            title="Return to Public Website"
          >
            <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
              <path d="M3 9l9-7 9 7v11a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2z" />
              <polyline points="9 22 9 12 15 12 15 22" />
            </svg>
            <span>Home</span>
          </button>

          {onLogout && (
            <button
              type="button"
              className="student-sidebar-footer-btn"
              onClick={onLogout}
              title="Sign Out"
            >
              <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
                <path d="M9 21H5a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2h4" />
                <polyline points="16 17 21 12 16 7" />
                <line x1="21" y1="12" x2="9" y2="12" />
              </svg>
              <span>Exit</span>
            </button>
          )}
        </div>
      </div>
    </aside>
  );
}
